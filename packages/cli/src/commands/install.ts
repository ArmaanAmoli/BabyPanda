import {
	appendFileSync,
	chmodSync,
	copyFileSync,
	existsSync,
	accessSync,
	constants,
	lstatSync,
	mkdirSync,
	readFileSync,
	realpathSync,
	rmSync,
	symlinkSync,
	writeFileSync,
} from 'node:fs';
import {homedir} from 'node:os';
import path from 'node:path';
import {COMMAND_NAME} from './usage';

/** Marker every generated wrapper carries, so `uninstall` can recognise ours. */
const WRAPPER_MARKER = `# Generated by \`${COMMAND_NAME} install\`.`;

/** Directories that are on PATH for every user of the machine, best first. */
const SYSTEM_DIRECTORIES = ['/usr/local/bin', '/usr/bin'];

/** Per-user fallbacks, used when no system directory is writable. */
const USER_DIRECTORIES = ['.local/bin', '.bin'];

/** Interpreters a script can be run through instead of being linked directly. */
const RUNTIME_EXECUTABLES = new Set([
	'bun',
	'bunx',
	'node',
	'deno',
	'tsx',
	'ts-node',
]);

const SCRIPT_EXTENSIONS = new Set([
	'.ts',
	'.tsx',
	'.js',
	'.jsx',
	'.mjs',
	'.cjs',
]);

/**
 * What `babypanda install` should put on PATH.
 *
 * A compiled binary is linked (or copied) as-is. When the CLI is run straight
 * from a checkout — `bun packages/cli/src/cli.tsx` — there is no binary to
 * link, so a wrapper script is written that execs the interpreter on the
 * entrypoint.
 */
export type CommandTarget =
	| {kind: 'executable'; path: string}
	| {kind: 'wrapper'; runtime: string; script: string};

function isScriptFile(candidate: string): boolean {
	if (!SCRIPT_EXTENSIONS.has(path.extname(candidate).toLowerCase())) {
		return false;
	}
	return existsSync(path.resolve(candidate));
}

export function resolveCommandTarget(
	execPath: string = process.execPath,
	argv: readonly string[] = process.argv,
): CommandTarget {
	const runtime = path.basename(execPath).replace(/\.(exe|cmd|bat)$/i, '');
	const script = argv[1];
	if (
		RUNTIME_EXECUTABLES.has(runtime) &&
		script !== undefined &&
		script !== '' &&
		isScriptFile(script)
	) {
		return {kind: 'wrapper', runtime: execPath, script: path.resolve(script)};
	}
	return {kind: 'executable', path: execPath};
}

/** POSIX single-quote, safe for paths containing spaces or quotes. */
export function shellQuote(value: string): string {
	return `'${value.replaceAll("'", `'\\''`)}'`;
}

export function renderWrapper(
	target: Extract<CommandTarget, {kind: 'wrapper'}>,
): string {
	return [
		'#!/bin/sh',
		WRAPPER_MARKER,
		'# Re-run `babypanda install --force` if this checkout moves.',
		`exec ${shellQuote(target.runtime)} ${shellQuote(target.script)} "$@"`,
		'',
	].join('\n');
}

export interface InstallLocation {
	directory: string;
	/** Whether the directory is already on PATH. */
	onPath: boolean;
	/** Whether the directory has to be created first. */
	created: boolean;
}

function isWritable(directory: string): boolean {
	try {
		accessSync(directory, constants.W_OK);
		return true;
	} catch {
		return false;
	}
}

function canCreate(directory: string): boolean {
	const parent = path.dirname(directory);
	return existsSync(parent) && isWritable(parent);
}

function isUsable(directory: string): boolean {
	return existsSync(directory) ? isWritable(directory) : canCreate(directory);
}

/**
 * Whether `directory` is one of the entries of `pathEntries`.
 *
 * Empty entries are skipped: a shell reads them as "the current directory",
 * but resolving one would make every directory look like it is on PATH.
 */
export function isOnPath(
	directory: string,
	pathEntries: string = process.env['PATH'] ?? '',
): boolean {
	const resolved = path.resolve(directory);
	return pathEntries
		.split(path.delimiter)
		.some(entry => entry !== '' && path.resolve(entry) === resolved);
}

/**
 * Where the command should be registered.
 *
 * An explicit `--dir` (or `BABY_PANDA_BIN_DIR`) always wins. Otherwise the
 * first system directory that is writable and already on PATH is preferred, so
 * the command works for every shell without further setup; a per-user
 * directory is the fallback when the process has no write access there.
 */
export function resolveInstallDirectory(
	explicit?: string,
): InstallLocation | {error: string} {
	const requested = explicit ?? process.env['BABY_PANDA_BIN_DIR'];
	if (requested !== undefined && requested !== '') {
		const directory = path.resolve(requested);
		if (!isUsable(directory)) {
			return {error: `${directory} is not writable and cannot be created`};
		}
		return {
			directory,
			onPath: isOnPath(directory),
			created: !existsSync(directory),
		};
	}

	const candidates = [
		...SYSTEM_DIRECTORIES,
		...USER_DIRECTORIES.map(relative => path.join(homedir(), relative)),
	];
	const usable = candidates.filter(isUsable);
	const preferred = usable.find(directory => isOnPath(directory)) ?? usable[0];
	if (preferred === undefined) {
		return {
			error:
				`no writable directory on PATH to install ${COMMAND_NAME} into. ` +
				`Pick one yourself, for example:\n` +
				`  ${COMMAND_NAME} install --dir ~/.local/bin --add-to-path`,
		};
	}
	return {
		directory: preferred,
		onPath: isOnPath(preferred),
		created: !existsSync(preferred),
	};
}

function isSymlink(candidate: string): boolean {
	try {
		return lstatSync(candidate).isSymbolicLink();
	} catch {
		return false;
	}
}

function pathExists(candidate: string): boolean {
	// existsSync is false for a dangling symlink, which still has to be replaced
	return existsSync(candidate) || isSymlink(candidate);
}

function shellRcFile(directory: string): {file: string; line: string} {
	const shell = path.basename(process.env['SHELL'] ?? '');
	if (shell === 'fish') {
		return {
			file: path.join(homedir(), '.config', 'fish', 'config.fish'),
			line: `fish_add_path ${shellQuote(directory)}`,
		};
	}
	const file =
		shell === 'zsh'
			? path.join(homedir(), '.zshrc')
			: path.join(homedir(), shell === 'bash' ? '.bashrc' : '.profile');
	return {file, line: `export PATH="${directory}:$PATH"`};
}

function appendToShellRc(directory: string): {file: string} | {error: string} {
	const {file, line} = shellRcFile(directory);
	const existing = existsSync(file) ? readFileSync(file, 'utf8') : '';
	if (existing.split('\n').includes(line)) {
		return {file};
	}
	try {
		const separator = existing === '' || existing.endsWith('\n') ? '' : '\n';
		appendFileSync(file, `${separator}${line}\n`);
	} catch (error) {
		return {error: `could not update ${file}: ${String(error)}`};
	}
	return {file};
}

export interface InstallOptions {
	/** Install here instead of the resolved default. */
	directory?: string;
	/** Copy the executable instead of symlinking it. */
	copy?: boolean;
	/** Replace an existing registration. */
	force?: boolean;
	/** Append the install directory to the shell rc when it is not on PATH. */
	addToPath?: boolean;
}

/** `babypanda install`: put `babypanda` on this computer's PATH. */
export async function installCommand(
	options: InstallOptions = {},
): Promise<number> {
	const target = resolveCommandTarget();
	const location = resolveInstallDirectory(options.directory);
	if ('error' in location) {
		process.stderr.write(`${location.error}\n`);
		return 1;
	}

	const linkPath = path.join(location.directory, COMMAND_NAME);
	if (pathExists(linkPath)) {
		if (!options.force) {
			process.stderr.write(`${linkPath} already exists.\n`);
			process.stderr.write(`Re-run with --force to replace it.\n`);
			return 1;
		}
		rmSync(linkPath, {force: true});
	}

	if (location.created) {
		mkdirSync(location.directory, {recursive: true});
	}

	if (target.kind === 'wrapper') {
		writeFileSync(linkPath, renderWrapper(target));
	} else if (options.copy) {
		copyFileSync(target.path, linkPath);
	} else {
		try {
			symlinkSync(target.path, linkPath);
		} catch (error) {
			const code = (error as {code?: string}).code;
			if (code !== 'EPERM' && code !== 'ENOSYS' && code !== 'EOPNOTSUPP') {
				throw error;
			}
			// Some filesystems and containers refuse symlinks outright; a copy
			// is the only registration that works there.
			copyFileSync(target.path, linkPath);
		}
	}
	chmodSync(linkPath, 0o755);

	process.stdout.write(`Registered ${COMMAND_NAME} at ${linkPath}\n`);
	process.stdout.write(
		`  -> ${target.kind === 'wrapper' ? target.script : target.path}\n`,
	);
	if (target.kind === 'wrapper') {
		process.stdout.write(
			'  wrapper script: it runs this checkout in place, so keep it where it is\n',
		);
	}

	if (!location.onPath) {
		process.stdout.write(`\n${location.directory} is not on your PATH.\n`);
		if (options.addToPath) {
			const appended = appendToShellRc(location.directory);
			if ('error' in appended) {
				process.stderr.write(`${appended.error}\n`);
				return 1;
			}
			process.stdout.write(
				`Added it to ${appended.file} — restart your shell to pick it up.\n`,
			);
		} else {
			process.stdout.write(`Add it yourself, for example:\n`);
			process.stdout.write(
				`  echo 'export PATH="${location.directory}:$PATH"' >> ~/.bashrc\n`,
			);
			process.stdout.write(
				`Or re-run with --add-to-path to have it done for you.\n`,
			);
		}
	}

	process.stdout.write(
		`\nRun \`${COMMAND_NAME} help\` to see what it can do.\n`,
	);
	return 0;
}

export interface UninstallOptions {
	/** Remove the registration from here instead of the resolved default. */
	directory?: string;
	/** Remove a registration that was not created by `babypanda install`. */
	force?: boolean;
}

function isOurRegistration(linkPath: string, target: CommandTarget): boolean {
	if (isSymlink(linkPath)) {
		if (target.kind !== 'executable') {
			return false;
		}
		try {
			return realpathSync(linkPath) === realpathSync(target.path);
		} catch {
			return false;
		}
	}
	try {
		return readFileSync(linkPath, 'utf8').includes(WRAPPER_MARKER);
	} catch {
		return false;
	}
}

/** `babypanda uninstall`: take `babypanda` off this computer's PATH. */
export async function uninstallCommand(
	options: UninstallOptions = {},
): Promise<number> {
	const location = resolveInstallDirectory(options.directory);
	if ('error' in location) {
		process.stderr.write(`${location.error}\n`);
		return 1;
	}

	const linkPath = path.join(location.directory, COMMAND_NAME);
	if (!pathExists(linkPath)) {
		process.stdout.write(
			`${COMMAND_NAME} is not installed in ${location.directory}\n`,
		);
		return 0;
	}

	if (!options.force && !isOurRegistration(linkPath, resolveCommandTarget())) {
		process.stderr.write(`${linkPath} was not installed by ${COMMAND_NAME}.\n`);
		process.stderr.write('Remove it by hand, or re-run with --force.\n');
		return 1;
	}

	rmSync(linkPath, {force: true});
	process.stdout.write(`Removed ${linkPath}\n`);
	return 0;
}
