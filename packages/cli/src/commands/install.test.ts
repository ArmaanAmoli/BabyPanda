import {describe, expect, test} from 'bun:test';
import {mkdtempSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {
	isOnPath,
	renderWrapper,
	resolveCommandTarget,
	resolveInstallDirectory,
	shellQuote,
} from './install';

/** A real file on disk, because the resolver checks the script really exists. */
function scriptFile(name: string): string {
	const directory = mkdtempSync(path.join(tmpdir(), 'babypanda-install-'));
	const file = path.join(directory, name);
	writeFileSync(file, '// placeholder\n');
	return file;
}

describe('resolveCommandTarget', () => {
	test('a compiled binary is linked directly', () => {
		expect(
			resolveCommandTarget('/opt/babypanda/bin/babypanda', [
				'/opt/babypanda/bin/babypanda',
				'list',
			]),
		).toEqual({kind: 'executable', path: '/opt/babypanda/bin/babypanda'});
	});

	test('a script run through bun becomes a wrapper', () => {
		const script = scriptFile('cli.tsx');
		expect(
			resolveCommandTarget('/home/me/.bun/bin/bun', [
				'/home/me/.bun/bin/bun',
				script,
			]),
		).toEqual({kind: 'wrapper', runtime: '/home/me/.bun/bin/bun', script});
	});

	test('a script run through node becomes a wrapper', () => {
		const script = scriptFile('cli.js');
		expect(
			resolveCommandTarget('/usr/bin/node', ['/usr/bin/node', script]),
		).toEqual({
			kind: 'wrapper',
			runtime: '/usr/bin/node',
			script,
		});
	});

	test('a runtime with no script argument is still an executable', () => {
		// a compiled binary reports argv[0] as a literal "bun" and argv[1] as
		// its embedded entrypoint, so the runtime name alone must never be
		// enough to build a wrapper
		expect(
			resolveCommandTarget('/opt/babypanda/bin/babypanda', ['bun']),
		).toEqual({
			kind: 'executable',
			path: '/opt/babypanda/bin/babypanda',
		});
	});

	test('a compiled binary is not mistaken for a script run', () => {
		expect(
			resolveCommandTarget('/opt/babypanda/bin/babypanda', [
				'bun',
				'/$bunfs/root/babypanda',
				'list',
			]),
		).toEqual({kind: 'executable', path: '/opt/babypanda/bin/babypanda'});
	});

	test('a runtime pointed at a non-script file is an executable', () => {
		const notAScript = scriptFile('README.md');
		expect(
			resolveCommandTarget('/usr/bin/bun', ['/usr/bin/bun', notAScript]),
		).toEqual({
			kind: 'executable',
			path: '/usr/bin/bun',
		});
	});

	test('a runtime pointed at a missing script file is an executable', () => {
		expect(
			resolveCommandTarget('/usr/bin/bun', [
				'/usr/bin/bun',
				'/repo/gone/cli.tsx',
			]),
		).toEqual({kind: 'executable', path: '/usr/bin/bun'});
	});
});

describe('shellQuote', () => {
	test('wraps in single quotes', () => {
		expect(shellQuote('/usr/local/bin')).toBe("'/usr/local/bin'");
	});

	test('escapes an embedded single quote the POSIX way', () => {
		expect(shellQuote("/it's here")).toBe(`'/it'\\''s here'`);
	});

	test('leaves spaces alone inside the quotes', () => {
		expect(shellQuote('/opt/my apps/babypanda')).toBe(
			"'/opt/my apps/babypanda'",
		);
	});
});

describe('renderWrapper', () => {
	test('execs the runtime on the script and forwards every argument', () => {
		const wrapper = renderWrapper({
			kind: 'wrapper',
			runtime: '/home/me/.bun/bin/bun',
			script: '/repo/packages/cli/src/cli.tsx',
		});
		const lines = wrapper.split('\n');
		expect(lines[0]).toBe('#!/bin/sh');
		expect(lines.at(-1)).toBe('');
		expect(wrapper).toContain(
			`exec '/home/me/.bun/bin/bun' '/repo/packages/cli/src/cli.tsx' "$@"`,
		);
	});

	test('carries the marker uninstall looks for', () => {
		const wrapper = renderWrapper({
			kind: 'wrapper',
			runtime: 'bun',
			script: '/repo/cli.tsx',
		});
		expect(wrapper).toContain('Generated by `babypanda install`');
	});
});

describe('isOnPath', () => {
	test('matches a directory listed on PATH', () => {
		expect(isOnPath('/usr/local/bin', '/usr/bin:/usr/local/bin:/bin')).toBe(
			true,
		);
	});

	test('rejects a directory that is not listed', () => {
		expect(isOnPath('/definitely/not/on/path', '/usr/bin:/usr/local/bin')).toBe(
			false,
		);
	});

	test('ignores empty PATH entries rather than matching the cwd', () => {
		expect(isOnPath(process.cwd(), ':')).toBe(false);
	});

	test('compares resolved paths, so a trailing slash still matches', () => {
		expect(isOnPath('/usr/local/bin/', '/usr/local/bin')).toBe(true);
	});
});

describe('resolveInstallDirectory', () => {
	test('an explicit directory always wins', () => {
		const location = resolveInstallDirectory(tmpdir());
		expect('error' in location).toBe(false);
		expect(!('error' in location) && location.directory).toBe(tmpdir());
	});

	test('an explicit directory is rejected when it cannot be created', () => {
		const location = resolveInstallDirectory('/proc/definitely/not/writable');
		expect('error' in location).toBe(true);
	});
});
